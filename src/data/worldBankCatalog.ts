export function resolveCountryIso3(countryName?: string | null, rawCode?: string | null): string {
  if (rawCode) {
    const trimmed = rawCode.trim().toUpperCase();
    if (/^[A-Z]{3}$/.test(trimmed)) {
      return trimmed;
    }
  }
  if (!countryName) return 'UNK';
  const cleaned = countryName
    .toLowerCase()
    .replace(/\([^)]*\)/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (COUNTRY_NAME_TO_ISO3[cleaned]) {
    return COUNTRY_NAME_TO_ISO3[cleaned];
  }
  return cleaned.replace(/[^a-z0-9]/g, '_').toUpperCase().slice(0, 12) || 'UNK';
}

